window.verifyStateAndDesign = async () => {
    const results = [];
    const check = (value, name) => { if (!value) throw new Error(name); results.push(name); };
    const get = async () => (await fetch('/api/v1/chats/messages/proof-mockup/visualizations/mockup/state')).json();
    const probe = inspectExample;
    document.querySelector('[data-preview-action="design"]').click();
    await probe();
    let state = await probe({selector:'[data-design-group="focus-card"] [data-design-property="radius"]',value:'30',event:'input'});
    check(state.cards['focus-card'].radius === '30px', 'slider updates bound rendering');
    state = await probe({selector:'[data-design-group="focus-card"] [data-design-property="accent"]',value:'#339d8b',event:'input'});
    check(state.cards['focus-card'].accent === '#339d8b', 'color picker updates rendering');
    state = await probe({selector:'[data-design-group="focus-card"] [data-design-property="hint"]',checked:false,event:'input'});
    check(!state.cards['focus-card'].hint, 'toggle updates rendering');
    state = await probe({selector:'[data-design-group="focus-card"] [data-design-property="heading"]',value:'Bold',event:'input'});
    check(state.cards['focus-card'].heading === '30px', 'select updates rendering');
    await OmlorixVisualizer.flushState();
    let saved = await get();
    check(saved.design.values['focus-card'].radius === 30, 'production state service persists design values');
    const revision = saved.revision;
    state = await probe({selector:'.omlorix-design-panel .viz-controls button:nth-child(1)',event:'click'});
    check(state.cards['focus-card'].radius === '18px' && state.cards['focus-card'].hint, 'original preview temporarily restores defaults');
    await OmlorixVisualizer.flushState();
    check((await get()).revision === revision, 'original preview does not overwrite saved design');
    state = await probe({selector:'.omlorix-design-panel .viz-controls button:nth-child(1)',event:'click'});
    check(state.cards['focus-card'].radius === '30px' && !state.cards['focus-card'].hint, 'leaving original restores edits');
    state = await probe({selector:'.omlorix-variant-nav select',value:'Discover',event:'change'});
    check(state.variants.find(v => v.name === 'Discover').hidden === false, 'named variant picker selects Discover');
    check(state.designGroups.join() === 'discover-card', 'only active variant control group is visible');
    state = await probe({selector:'[data-design-group="discover-card"] [data-design-property="radius"]',value:'8',event:'input'});
    check(state.cards['discover-card'].radius === '8px', 'variants have independent editable values');
    state = await probe({selector:'.omlorix-variant-nav select',value:'Focus',event:'change'});
    check(state.cards['focus-card'].radius === '30px', 'switching variants preserves DOM and prior edits');
    await OmlorixVisualizer.flushState();
    saved = await get();
    check(saved.design.variants['workspace-directions'] === 'Focus', 'variant selection is persisted');
    await probe({selector:'.omlorix-design-panel .viz-controls button:nth-child(3)',event:'click'});
    await new Promise(resolve => setTimeout(resolve, 80));
    check(proofConfirmation?.copyText.includes('border-radius') && !window.proofSentPrompt, 'Apply in chat prepares named changes and respects cancelled confirmation');
    window.proofApprove = true;
    await probe({selector:'.omlorix-design-panel .viz-controls button:nth-child(3)',event:'click'});
    await new Promise(resolve => setTimeout(resolve, 80));
    check(proofSentPrompt?.includes('Focus') && proofSentPrompt.includes('30'), 'confirmed changes reach the follow-up bridge');
    check(!state.overflow && state.remoteResources.length === 0, 'controls fit the frame without external requests');
    return results;
};
