function launcherLocale(locale = "en") {
  const language = String(locale || "en")
    .toLowerCase()
    .split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(NATIVE_LAUNCHER_ROWS, language)
    ? language
    : "en";
}

